// Builds the static reference catalog from the TidyTuesday Parfumo CSV (kept out of git).
//   npm run build-catalog -- /path/to/parfumo.csv
// Writes public/catalog/catalog-<hash>.json and src/lib/catalog-manifest.ts. The filename
// changes with the content, so the file can be cached forever.
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { cleanRows, CSV_URL, dedupeRows, encodeCatalog, isUseful } from './lib/parfumo';

const OUT_DIR = 'public/catalog';
const MANIFEST = 'src/lib/catalog-manifest.ts';
// The source's last update. Fixed, so that rebuilding unchanged data gives an identical file.
const SOURCE_DATE = '2024-12-10';

function main() {
  const csvPath = process.argv[2];
  if (!csvPath) {
    console.error(`Usage: npm run build-catalog -- /path/to/parfumo.csv\nSource: ${CSV_URL}`);
    process.exit(1);
  }
  const { rows, stats } = cleanRows(readFileSync(csvPath, 'utf8'));
  const useful = rows.filter(isUseful);
  const kept = dedupeRows(useful);
  const body = JSON.stringify(encodeCatalog(kept, SOURCE_DATE));

  const hash = createHash('sha256').update(body).digest('hex').slice(0, 10);
  const file = `catalog-${hash}.json`;
  mkdirSync(OUT_DIR, { recursive: true });
  for (const old of readdirSync(OUT_DIR)) if (/^catalog-.*\.json$/.test(old)) rmSync(join(OUT_DIR, old));
  writeFileSync(join(OUT_DIR, file), body);
  writeFileSync(
    MANIFEST,
    `// Generated by scripts/build-catalog.ts. Do not edit.\nexport const CATALOG_FILE = '${file}';\n`,
  );

  const raw = Buffer.byteLength(body);
  const gz = gzipSync(body, { level: 9 }).length;
  console.log(stats);
  console.log(`no data to offer: ${rows.length - useful.length}, duplicates: ${useful.length - kept.length}`);
  console.log(`entries: ${kept.length}, brands: ${new Set(kept.map((r) => r.brand)).size}`);
  console.log(`${file}: ${(raw / 1e6).toFixed(2)} MB raw, ${(gz / 1e6).toFixed(2)} MB gzipped`);
}

main();
